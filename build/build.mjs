#!/usr/bin/env node
/* Build self-contained single files from linked sources.

     node build/build.mjs           build, lint, write
     node build/build.mjs --check   build, lint, compare — writes nothing (CI)

   Two targets:
     widgets/src/*.html       -> widgets/*.html          shipped widgets
     design-system/src/*.html -> design-system/*.html    Claude Design cards

   Files whose name starts with "_" are partials — linked by the pages that
   need them, never built on their own.

   Output is deterministic: no timestamps, no ordering by mtime. --check is
   therefore a real drift test, not a coin flip. */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve, basename } from "node:path";
import { inlineHtml } from "./inline.mjs";
import { lintBuilt, formatReport } from "./lint.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const TARGETS = [
  { src: "widgets/src", out: "widgets" },
  { src: "design-system/src", out: "design-system" },
];

const check = process.argv.includes("--check");

/* Claude Design reads a card's group from an @dsCard comment on the FIRST
   line of the file, so the build banner has to give up its usual spot. */
const DS_CARD = /^\s*<!--\s*@dsCard\b[^>]*-->[ \t]*\r?\n/;

const banner = (srcRel, inlined) =>
  `<!-- Built from ${srcRel} by build/build.mjs. Do not edit this file.\n` +
  `     Inlined: ${inlined.join(", ") || "nothing"}\n` +
  `     Self-contained: no network requests, works when opened from disk. -->\n`;

const withBanner = (html, srcRel, inlined) => {
  const text = banner(srcRel, inlined);
  const card = html.match(DS_CARD);
  return card ? card[0] + text + html.slice(card[0].length) : text + html;
};

const listSources = async (dir) => {
  try {
    return (await readdir(dir))
      .filter((f) => f.endsWith(".html") && !basename(f).startsWith("_"))
      .sort();
  } catch {
    return null;
  }
};

const main = async () => {
  const results = [];
  const drifted = [];
  const built = [];
  let found = 0;

  for (const target of TARGETS) {
    const srcDir = join(ROOT, target.src);
    const outDir = join(ROOT, target.out);
    const sources = await listSources(srcDir);
    if (sources === null) continue;
    found += sources.length;
    if (!sources.length) continue;

    if (!check) await mkdir(outDir, { recursive: true });

    for (const name of sources) {
      const srcRel = `${target.src}/${name}`;
      const { html, inlined } = await inlineHtml(join(srcDir, name), ROOT);
      const output = withBanner(html.replace(/\r\n/g, "\n").trimEnd() + "\n", srcRel, inlined);
      const outRel = `${target.out}/${name}`;
      const outPath = join(outDir, name);

      results.push(lintBuilt(output, outRel));

      if (check) {
        let existing = null;
        try { existing = await readFile(outPath, "utf8"); } catch {}
        if (existing !== output) drifted.push(outRel);
      } else {
        await writeFile(outPath, output, "utf8");
        built.push({ path: outRel, bytes: output.length });
      }
    }
  }

  if (!found) {
    console.error("No sources found. Widget sources live in widgets/src/, design cards in design-system/src/.");
    process.exit(1);
  }

  const report = formatReport(results);
  console.log(report.text);

  if (!check && built.length) {
    console.log("");
    for (const b of built) console.log(`  ${(b.bytes / 1024).toFixed(1).padStart(6)} KB  ${b.path}`);
  }

  if (report.errors) {
    console.error(`\n${report.errors} constraint error(s). Nothing shipped.`);
    process.exit(1);
  }
  if (drifted.length) {
    console.error(`\nBuilt output is stale: ${drifted.join(", ")}. Run \`npm run build\` and commit.`);
    process.exit(1);
  }
  console.log(
    check
      ? `\n${results.length} file(s) up to date, ${report.warnings} warning(s).`
      : `\n${built.length} file(s) built, ${report.warnings} warning(s).`
  );
};

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
