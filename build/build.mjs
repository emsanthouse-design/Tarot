#!/usr/bin/env node
/* Build widgets/src/*.html -> widgets/*.html as self-contained single files.

     node build/build.mjs           build, lint, write
     node build/build.mjs --check   build, lint, compare — writes nothing (CI)

   Output is deterministic: no timestamps, no ordering by mtime. --check is
   therefore a real drift test, not a coin flip. */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve, basename } from "node:path";
import { inlineHtml } from "./inline.mjs";
import { lintBuilt, formatReport } from "./lint.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC_DIR = join(ROOT, "widgets", "src");
const OUT_DIR = join(ROOT, "widgets");

const check = process.argv.includes("--check");

const banner = (name, inlined) =>
  `<!-- Built from widgets/src/${name} by build/build.mjs. Do not edit this file.\n` +
  `     Inlined: ${inlined.join(", ") || "nothing"}\n` +
  `     Self-contained: no network requests, works when opened from disk. -->\n`;

const main = async () => {
  let sources;
  try {
    sources = (await readdir(SRC_DIR)).filter((f) => f.endsWith(".html")).sort();
  } catch {
    console.error(`No widgets/src/ directory. Widget sources live there; built files land in widgets/.`);
    process.exit(1);
  }

  if (!sources.length) {
    console.error("widgets/src/ holds no .html sources — nothing to build.");
    process.exit(1);
  }

  await mkdir(OUT_DIR, { recursive: true });

  const results = [];
  const drifted = [];
  let wrote = 0;

  for (const name of sources) {
    const { html, inlined } = await inlineHtml(join(SRC_DIR, name), ROOT);
    const output = banner(name, inlined) + html.replace(/\r\n/g, "\n").trimEnd() + "\n";
    const outPath = join(OUT_DIR, basename(name));

    results.push(lintBuilt(output, `widgets/${basename(name)}`));

    if (check) {
      let existing = null;
      try { existing = await readFile(outPath, "utf8"); } catch {}
      if (existing !== output) drifted.push(`widgets/${basename(name)}`);
    } else {
      await writeFile(outPath, output, "utf8");
      wrote++;
    }
  }

  const report = formatReport(results);
  console.log(report.text);

  const bytes = async (n) => {
    try { return (await readFile(join(OUT_DIR, n), "utf8")).length; } catch { return 0; }
  };
  if (!check) {
    for (const name of sources) {
      console.log(`  ${(await bytes(name) / 1024).toFixed(1)} KB  widgets/${name}`);
    }
  }

  if (report.errors) {
    console.error(`\n${report.errors} constraint error(s). Nothing shipped.`);
    process.exit(1);
  }
  if (drifted.length) {
    console.error(`\nBuilt output is stale: ${drifted.join(", ")}. Run \`npm run build\` and commit.`);
    process.exit(1);
  }
  console.log(
    check
      ? `\n${sources.length} widget(s) up to date, ${report.warnings} warning(s).`
      : `\n${wrote} widget(s) built, ${report.warnings} warning(s).`
  );
};

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
