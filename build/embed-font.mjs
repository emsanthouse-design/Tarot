#!/usr/bin/env node
/* Regenerate fonts/tarot-font-embed.css from fonts/Tarot-Regular.ttf.

     node build/embed-font.mjs           rewrite the embed
     node build/embed-font.mjs --check   verify it matches the .ttf (CI)

   The embed is a generated artifact that is committed, because the build
   inlines it and a fresh checkout has to work. Committed generated files
   drift; this is what stops that.

   Both vendor files carry TrueType outlines (sfnt signature 0x00010000)
   despite the .otf extension, so format("truetype") is correct for both.
   We use the .ttf. */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TTF = join(ROOT, "fonts", "Tarot-Regular.ttf");
const OUT = join(ROOT, "fonts", "tarot-font-embed.css");

const HEADER = `/* The Tarot Revue — self-contained @font-face for Tarot Regular.
   The .ttf is embedded as a base64 data URI so a widget can be a single
   HTML file with no external requests. This is required for Notion, which
   strips external scripts and will not fetch a sibling font file.

   Note: both files shipped by the vendor as .otf and .ttf carry TrueType
   outlines (sfnt signature 0x00010000), so format('truetype') is correct
   for both. Use the .ttf.

   GENERATED by build/embed-font.mjs from fonts/Tarot-Regular.ttf.
   Do not hand-edit — run \`npm run embed-font\` instead.

   Usage rules live in docs/design-system.md section 2. Short version:
   cover titles, major titles, section openers, occasional theatrical
   labels. Never body copy, UI, tables, or long headings. Two appearances
   per view, maximum. */
`;

const main = async () => {
  const ttf = await readFile(TTF);
  const sig = ttf.readUInt32BE(0);
  if (sig !== 0x00010000 && sig !== 0x4f54544f) {
    throw new Error(`fonts/Tarot-Regular.ttf is not an sfnt font (signature 0x${sig.toString(16)}).`);
  }
  const format = sig === 0x00010000 ? "truetype" : "opentype";

  const css =
    HEADER +
    `\n@font-face {\n` +
    `  font-family: "Tarot";\n` +
    `  font-style: normal;\n` +
    `  font-weight: 400;\n` +
    `  font-display: swap;\n` +
    `  src: url(data:font/ttf;base64,${ttf.toString("base64")}) format("${format}");\n` +
    `}\n`;

  if (process.argv.includes("--check")) {
    let existing = null;
    try { existing = await readFile(OUT, "utf8"); } catch {}
    if (existing !== css) {
      console.error("fonts/tarot-font-embed.css does not match fonts/Tarot-Regular.ttf. Run `npm run embed-font`.");
      process.exit(1);
    }
    console.log(`  ok    fonts/tarot-font-embed.css matches the .ttf (${ttf.length} bytes, format "${format}")`);
    return;
  }

  await writeFile(OUT, css, "utf8");
  console.log(`  wrote fonts/tarot-font-embed.css — ${ttf.length} bytes of font, format "${format}"`);
};

main().catch((e) => { console.error(e.message || e); process.exit(1); });
